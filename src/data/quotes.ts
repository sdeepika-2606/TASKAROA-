export const getRandomQuote = (previousQuoteText?: string): Quote => {
  let filteredQuotes = quotes.filter(q => q.text !== previousQuoteText);
  if (filteredQuotes.length === 0) filteredQuotes = quotes;
  return filteredQuotes[Math.floor(Math.random() * filteredQuotes.length)];
};
